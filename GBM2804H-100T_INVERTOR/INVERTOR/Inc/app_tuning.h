/**
 * Подстройка привода под стенд P-NUCLEO-IHM03 (гимбальный двигатель без нагрузки).
 *
 * Значения, сгенерированные MC Workbench (drive_parameters.h), рассчитаны на «средний» двигатель.
 * У гимбального ротора очень малая инерция: при передаче управления наблюдателю
 * вектор тока поворачивается с оси d на ось q и за 25 мс разгоняет ротор на +1000 об/мин,
 * а мягкий ПИ скорости не успевает его удержать — наблюдатель выдаёт SPEEDFBK.
 *
 * Переопределения применяются в MC_APP_BootHook через API MCSDK, поэтому переживают
 * повторную генерацию проекта. Чтобы вернуть значения Workbench, закомментируйте вызов
 * APP_TUNING_Apply() в Src/app_cli.c.
 */
#ifndef APP_TUNING_H
#define APP_TUNING_H

#include <stdint.h>

/* Ток разомкнутого контура (выравнивание, I/f-режим на малой скорости, пуск), А.
 * Workbench для rev-up: 1.348 А (NOMINAL_CURRENT). Без нагрузки хватает малого тока;
 * меньше ток — меньше нагрев при длительной работе внизу и меньше бросок при передаче
 * управления наблюдателю. Момент удержания при 0.7 А ~ 0.06 Нм. */
#define APP_OL_CURRENT_A         0.70f

/* Выравнивание ротора на пуске: ток плавно растёт 0 -> APP_OL_CURRENT_A за это время, угол стоит. */
#define APP_ALIGN_MS             600u

/* Гибридный контур (Src/app_hybrid.c).
 * Ниже APP_HYB_OPEN_RPM наблюдатель не видит ПЭДС (при 100 об/мин она ~0.5 В на фоне 15 В шины),
 * поэтому там работает разомкнутый I/f: угол задаётся интегрированием задания скорости,
 * ток фиксирован. Выше APP_HYB_CLOSE_RPM, когда наблюдатель сошёлся, управление передаётся ему.
 * Гистерезис между порогами исключает дребезг режимов. */
#define APP_HYB_CLOSE_RPM        600     /* разомкнутый -> наблюдатель (нужно > OBS_MINIMUM_SPEED_RPM 524) */
#define APP_HYB_OPEN_RPM         500     /* наблюдатель -> разомкнутый, по измеренной скорости */
#define APP_HYB_OL_MAX_RPM       900     /* потолок задания в разомкнутом контуре, если наблюдатель не сходится */
#define APP_HYB_PLL_RESET_RPM    200     /* ниже — интеграл ФАПЧ наблюдателя держится в нуле, как в фазе 1 rev-up */
#define APP_HYB_OL_MAX_RATE      400u    /* предел темпа задания в разомкнутом контуре, об/мин/с (ротор должен успевать) */
#define APP_HYB_CONVERGED_MS     50u     /* наблюдатель должен продержаться сошедшимся столько мс до сведения */
#define APP_HYB_BLEND_MS         100u    /* сведение угла виртуального датчика к углу наблюдателя */
#define APP_HYB_ID_DECAY_MS      300u    /* спад Id до нуля после замыкания контура */

/* ПИ скорости. Workbench: Kp = 2730 / 256, Ki = 562 / 16384 (на единицу 0.1 Гц, период 1 мс). */
#define APP_SPEED_KP             10920   /* x4: 42.7 цифры Iq на 6 об/мин ошибки */
#define APP_SPEED_KI             4496    /* x8: постоянная интегрирования Kp/Ki ~ 160 мс */

void APP_TUNING_Apply(void);

/* Ток разомкнутого контура в цифрах АЦП (не больше NOMINAL_CURRENT). */
int16_t APP_TUNING_OpenLoopCurrentDigits(void);

#endif /* APP_TUNING_H */
